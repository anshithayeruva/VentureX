-- VentureX schema on Lakebase Postgres (Neon).
-- Applied idempotently at API startup. Identity (users, sessions) lives in the
-- neon_auth schema managed by Neon Auth; app_users holds the app-specific role.

CREATE TABLE IF NOT EXISTS app_users (
    id            TEXT PRIMARY KEY,            -- Neon Auth user id (JWT "sub")
    email         TEXT NOT NULL,
    name          TEXT,
    role          TEXT CHECK (role IN ('FOUNDER', 'INVESTOR')),
    organization  TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS projects (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    founder_id              TEXT NOT NULL,
    title                   TEXT NOT NULL,
    tagline                 TEXT NOT NULL DEFAULT '',
    description             TEXT NOT NULL,
    problem                 TEXT NOT NULL,
    solution                TEXT NOT NULL,
    industry                TEXT NOT NULL,
    stage                   TEXT NOT NULL,
    funding_required        DOUBLE PRECISION NOT NULL DEFAULT 0,
    business_model          TEXT NOT NULL,
    target_market           TEXT NOT NULL,
    website                 TEXT NOT NULL DEFAULT '',
    pitch_deck_url          TEXT NOT NULL DEFAULT '',
    is_published            BOOLEAN NOT NULL DEFAULT FALSE,
    readiness_score         DOUBLE PRECISION,
    ai_readiness_breakdown  JSONB,
    ai_feedback_summary     TEXT,
    strengths               JSONB NOT NULL DEFAULT '[]',
    recommendations         JSONB NOT NULL DEFAULT '[]',
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS projects_founder_idx ON projects (founder_id);
CREATE INDEX IF NOT EXISTS projects_published_created_idx ON projects (is_published, created_at DESC);

CREATE TABLE IF NOT EXISTS founder_profiles (
    user_id     TEXT PRIMARY KEY,
    name        TEXT,
    company     TEXT,
    bio         TEXT,
    location    TEXT,
    linkedin    TEXT,
    website     TEXT,
    settings    JSONB NOT NULL DEFAULT '{}',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS investor_profiles (
    user_id     TEXT PRIMARY KEY,
    name        TEXT,
    firm        TEXT,
    title       TEXT,
    bio         TEXT,
    location    TEXT,
    thesis      TEXT,
    min_check   TEXT,
    max_check   TEXT,
    settings    JSONB NOT NULL DEFAULT '{}',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS investor_profiles_firm_idx ON investor_profiles (firm);

CREATE TABLE IF NOT EXISTS investor_preferences (
    investor_id                TEXT PRIMARY KEY,
    preferred_industries       JSONB NOT NULL DEFAULT '[]',
    preferred_stages           JSONB NOT NULL DEFAULT '[]',
    min_investment             DOUBLE PRECISION NOT NULL DEFAULT 500000,
    max_investment             DOUBLE PRECISION NOT NULL DEFAULT 1500000,
    preferred_business_models  JSONB NOT NULL DEFAULT '[]',
    geography                  TEXT NOT NULL DEFAULT 'North America & Europe',
    tech_preferences           JSONB NOT NULL DEFAULT '[]',
    created_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                 TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS matches (
    id             TEXT PRIMARY KEY,
    project_id     BIGINT NOT NULL,
    project_title  TEXT NOT NULL,
    investor_id    TEXT NOT NULL,
    investor_name  TEXT NOT NULL,
    investor_firm  TEXT,
    founder_id     TEXT,
    match_score    DOUBLE PRECISION NOT NULL,
    reasons        JSONB NOT NULL DEFAULT '[]',
    status         TEXT NOT NULL DEFAULT 'recommended',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (project_id, investor_id)
);
CREATE INDEX IF NOT EXISTS matches_score_idx ON matches (match_score DESC);
CREATE INDEX IF NOT EXISTS matches_investor_idx ON matches (investor_id, match_score DESC);

CREATE TABLE IF NOT EXISTS project_interests (
    id                TEXT PRIMARY KEY,
    project_id        BIGINT NOT NULL,
    project_title     TEXT,
    project_industry  TEXT,
    investor_id       TEXT NOT NULL,
    investor_name     TEXT,
    investor_firm     TEXT,
    investor_email    TEXT,
    founder_id        TEXT,
    founder_name      TEXT,
    founder_email     TEXT,
    status            TEXT NOT NULL DEFAULT 'pending',
    message           TEXT,
    response_note     TEXT,
    deal_room         JSONB,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (project_id, investor_id)
);
CREATE INDEX IF NOT EXISTS project_interests_founder_idx ON project_interests (founder_id, status);
CREATE INDEX IF NOT EXISTS project_interests_investor_idx ON project_interests (investor_id);

CREATE TABLE IF NOT EXISTS notifications (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id        TEXT,                        -- NULL = broadcast to the role
    target_role    TEXT,
    title          TEXT NOT NULL,
    "desc"         TEXT NOT NULL,
    badge          TEXT NOT NULL DEFAULT 'Alert',
    badge_variant  TEXT NOT NULL DEFAULT 'primary',
    link           TEXT,
    read           BOOLEAN NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS notifications_user_idx ON notifications (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS notifications_role_idx ON notifications (target_role, created_at DESC);

CREATE TABLE IF NOT EXISTS deal_rooms (
    id                          TEXT PRIMARY KEY,
    interest_id                 TEXT,
    project_id                  BIGINT NOT NULL,
    project_title               TEXT,
    project_industry            TEXT,
    founder_id                  TEXT NOT NULL,
    founder_name                TEXT,
    founder_email               TEXT,
    founder_company             TEXT,
    investor_id                 TEXT NOT NULL,
    investor_name               TEXT,
    investor_firm               TEXT,
    investor_email              TEXT,
    stage                       TEXT NOT NULL DEFAULT 'INTRO_ACCEPTED',
    nda_signed                  BOOLEAN NOT NULL DEFAULT FALSE,
    nda_signed_at               TIMESTAMPTZ,
    nda_signer_name             TEXT,
    shared_documents            JSONB NOT NULL DEFAULT '[]',
    last_message                TEXT,
    last_message_at             TIMESTAMPTZ,
    last_message_sender         TEXT,
    messages_count              INTEGER NOT NULL DEFAULT 0,
    audit_trail_hash            TEXT,
    is_secure_recording_active  BOOLEAN NOT NULL DEFAULT TRUE,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS deal_rooms_founder_idx ON deal_rooms (founder_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS deal_rooms_investor_idx ON deal_rooms (investor_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS deal_rooms_interest_idx ON deal_rooms (interest_id);

CREATE TABLE IF NOT EXISTS deal_room_messages (
    id              TEXT PRIMARY KEY,
    room_id         TEXT NOT NULL REFERENCES deal_rooms (id) ON DELETE CASCADE,
    sender_id       TEXT NOT NULL,
    sender_role     TEXT NOT NULL,
    sender_name     TEXT NOT NULL,
    content         TEXT NOT NULL,
    attachments     JSONB NOT NULL DEFAULT '[]',
    sequence        INTEGER NOT NULL,
    previous_hash   TEXT,
    integrity_hash  TEXT NOT NULL,
    is_read         BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (room_id, sequence)
);

CREATE TABLE IF NOT EXISTS deal_room_audit_logs (
    id           TEXT PRIMARY KEY,
    room_id      TEXT NOT NULL REFERENCES deal_rooms (id) ON DELETE CASCADE,
    event_type   TEXT NOT NULL,
    actor_id     TEXT NOT NULL,
    actor_role   TEXT NOT NULL,
    actor_name   TEXT,
    details      JSONB NOT NULL DEFAULT '{}',
    tamper_hash  TEXT,
    "timestamp"  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS deal_room_audit_logs_room_idx ON deal_room_audit_logs (room_id, "timestamp");

-- AI project intelligence -------------------------------------------------

ALTER TABLE projects ADD COLUMN IF NOT EXISTS github_url TEXT NOT NULL DEFAULT '';
ALTER TABLE projects ADD COLUMN IF NOT EXISTS demo_url TEXT NOT NULL DEFAULT '';

-- Materials a founder uploads for a project (pitch deck, business plan, ...).
-- The file lives in storage (`storage_path`); its extracted text is kept here
-- so analysis and search never have to re-parse it.
CREATE TABLE IF NOT EXISTS project_documents (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    project_id      BIGINT NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    category        TEXT NOT NULL DEFAULT 'supporting_document',
    original_name   TEXT NOT NULL,
    storage_path    TEXT NOT NULL,
    url             TEXT NOT NULL,
    content_type    TEXT NOT NULL,
    size_bytes      BIGINT NOT NULL,
    page_count      INTEGER,
    extracted_text  TEXT NOT NULL DEFAULT '',
    extraction_note TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS project_documents_project_idx ON project_documents (project_id, created_at);

-- Every readiness analysis run, newest last. projects.readiness_score and
-- friends mirror the latest row so list views stay a single query.
CREATE TABLE IF NOT EXISTS project_analyses (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    project_id       BIGINT NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    engine           TEXT NOT NULL,             -- 'claude' | 'rules'
    model            TEXT,
    overall_score    DOUBLE PRECISION NOT NULL,
    status_label     TEXT NOT NULL,
    summary          TEXT NOT NULL,
    dimensions       JSONB NOT NULL DEFAULT '[]',
    strengths        JSONB NOT NULL DEFAULT '[]',
    gaps             JSONB NOT NULL DEFAULT '[]',
    suggestions      JSONB NOT NULL DEFAULT '[]',
    industry_insights JSONB NOT NULL DEFAULT '[]',
    inputs           JSONB NOT NULL DEFAULT '{}', -- what the analysis saw (docs, github, ...)
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS project_analyses_project_idx ON project_analyses (project_id, created_at DESC);

