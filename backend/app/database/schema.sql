-- VentureX schema on Lakebase Postgres (Neon).
-- Applied idempotently at API startup. Identity (users, sessions) lives in the
-- neon_auth schema managed by Neon Auth; app_users holds the app-specific role.

CREATE TABLE IF NOT EXISTS app_users (
    id            TEXT PRIMARY KEY,            -- Neon Auth user id (JWT "sub")
    email         TEXT NOT NULL,
    name          TEXT,
    role          TEXT CHECK (role IN ('FOUNDER', 'INVESTOR')),
    organization  TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS projects (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    founder_id              TEXT NOT NULL,
    title                   TEXT NOT NULL,
    tagline                 TEXT NOT NULL DEFAULT '',
    description             TEXT NOT NULL,
    problem                 TEXT NOT NULL,
    solution                TEXT NOT NULL,
    industry                TEXT NOT NULL,
    stage                   TEXT NOT NULL,
    funding_required        DOUBLE PRECISION NOT NULL DEFAULT 0,
    business_model          TEXT NOT NULL,
    target_market           TEXT NOT NULL,
    website                 TEXT NOT NULL DEFAULT '',
    pitch_deck_url          TEXT NOT NULL DEFAULT '',
    is_published            BOOLEAN NOT NULL DEFAULT FALSE,
    readiness_score         DOUBLE PRECISION,
    ai_readiness_breakdown  JSONB,
    ai_feedback_summary     TEXT,
    strengths               JSONB NOT NULL DEFAULT '[]',
    recommendations         JSONB NOT NULL DEFAULT '[]',
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS projects_founder_idx ON projects (founder_id);
CREATE INDEX IF NOT EXISTS projects_published_created_idx ON projects (is_published, created_at DESC);

